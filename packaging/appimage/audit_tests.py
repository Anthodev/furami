#!/usr/bin/env python3
"""Behavioral tests for payload attribution, required entries and program closure."""
import hashlib
import importlib.util
import json
from pathlib import Path
import tempfile
import unittest

spec = importlib.util.spec_from_file_location('appimage_audit', Path(__file__).with_name('audit.py'))
audit = importlib.util.module_from_spec(spec)
spec.loader.exec_module(audit)


class QtAttributionTests(unittest.TestCase):
    def setUp(self):
        temporary = tempfile.TemporaryDirectory()
        self.addCleanup(temporary.cleanup)
        self.media = Path(temporary.name)
        self.prefix = self.media / 'prefix'
        self.prefix.mkdir()
        self.backend = self.file('lib/libQt6Example.so.6.11.2', b'checked vendor backend')
        self.file('qml/Builtin/Example/qmldir', b'module Builtin.Example\nstatic\nsystem\ntypeinfo types.qmltypes\n')
        self.file('qml/Builtin/Example/types.qmltypes', b'// This file was auto-generated by qmltyperegistrar.\nModule {}\n')
        self.file('lib/cmake/Qt6Example/Qt6ExampleTargets.cmake', b'''set_target_properties(Qt6::Example PROPERTIES
  _qt_qml_module_is_backing_target "TRUE"
  _qt_qml_module_installed_qmldir_path "qml/Builtin/Example/qmldir"
  _qt_qml_module_uri "Builtin.Example"
  _qt_sbom_spdx_id "SPDXRef-Example"
  _qt_sbom_spdx_v2_document_json_relative_path "sbom/qtbase-6.11.2.spdx.json"
  _qt_sbom_package_version "6.11.2"
)
''')
        self.document = {'name': 'qtbase', 'packages': [
            {'SPDXID': 'SPDXRef-Example', 'name': 'Example', 'versionInfo': '6.11.2',
             'licenseConcluded': 'LGPL-3.0-only'}],
            'files': [{'SPDXID': 'SPDXRef-Backend', 'fileName': './lib/libQt6Example.so.6.11.2',
                       'licenseConcluded': 'LGPL-3.0-only',
                       'checksums': [{'algorithm': 'SHA256', 'checksumValue': hashlib.sha256(self.backend.read_bytes()).hexdigest()}]}],
            'relationships': [{'spdxElementId': 'SPDXRef-Example', 'relatedSpdxElement': 'SPDXRef-Backend',
                               'relationshipType': 'CONTAINS'}]}
        self.documents()

    def file(self, relative, content):
        path = self.prefix / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(content)
        return path

    def documents(self):
        for name in ('qtbase', 'qtdeclarative', 'qtsvg', 'qtshadertools'):
            document = self.document if name == 'qtbase' else {'name': name, 'packages': [], 'files': [], 'relationships': []}
            self.file('sbom/' + name + '-6.11.2.spdx.json', json.dumps(document).encode())
        (self.media / 'manifest.json').write_text(json.dumps({'artifacts': {
            path.relative_to(self.prefix).as_posix(): {'sha256': audit.stage.digest(path)}
            for path in self.prefix.rglob('*') if path.is_file()}}))

    def owners(self):
        return {'usr/' + source: {'owner': 'media', 'source': source}
                for source in ('qml/Builtin/Example/qmldir', 'qml/Builtin/Example/types.qmltypes')}

    def test_builtin_metadata_uses_backend_component_without_inventing_file_terms(self):
        owners = self.owners()
        audit.qt_evidence(self.media, owners, self.media)
        for owner in owners.values():
            component = owner['components'][0]
            self.assertEqual(component['component_id'], 'qt:qtbase')
            self.assertIsNone(component['license_expression'])
            self.assertEqual(component['module_license_expression'], 'LGPL-3.0-only')
            self.assertEqual(component['evidence']['Qt_vendor_version'], '6.11.2')
            self.assertEqual(component['evidence']['package']['SPDXID'], 'SPDXRef-Example')
            self.assertEqual(component['evidence']['backend_files'][0]['file_spdx_id'], 'SPDXRef-Backend')

    def test_generated_terms_select_module_rule_without_inventing_file_license(self):
        owners = self.owners()
        qt = audit.qt_evidence(self.media, owners, self.media)
        providers = {'media': self.media}
        documents = {
            'app': {'crates': [], 'binary': {'rust_standard_library': {'archives': []}, 'direct_objects': []}},
            'runtime': {'components': []},
            'stage': {'packages': []}}
        for name, document in documents.items():
            directory = self.media / name
            directory.mkdir()
            providers[name] = directory
            filename = 'ubuntu-sources.json' if name == 'stage' else 'manifest.json'
            (directory / filename).write_text(json.dumps(document))
        registry, _, _ = audit.load('components').registry(providers, owners, qt, {'components': []}, audit.stage.digest)
        for owner in owners.values():
            component = owner['components'][0]
            self.assertEqual(component['source_component_id'], 'qt:qtbase')
            self.assertIsNone(component['license_expression'])
            self.assertEqual(component['selected_terms'], 'LGPL-3.0-only')
            self.assertTrue(component['terms_resolved'])
            self.assertEqual(component['terms_rule'], 'qt-qml-metadata-inherits-module-terms')
            self.assertEqual(registry[component['component_id']], component)

    def test_unrelated_vendor_backend_does_not_attribute_builtin_module(self):
        self.document['relationships'] = []
        self.documents()
        owners = self.owners()
        audit.qt_evidence(self.media, owners, self.media)
        self.assertTrue(all(owner['components'][0]['license_expression'] is None for owner in owners.values()))
        self.assertTrue(all(not owner['components'][0].get('terms_rule') for owner in owners.values()))

    def test_changed_generated_metadata_rejects_hash_chain(self):
        self.file('qml/Builtin/Example/types.qmltypes', b'changed metadata')
        with self.assertRaisesRegex(ValueError, 'QML provenance hash mismatch'):
            audit.qt_evidence(self.media, self.owners(), self.media)

    def test_missing_backend_checksum_does_not_admit_module_rule(self):
        self.document['files'][0]['checksums'] = []
        self.documents()
        owners = self.owners()
        audit.qt_evidence(self.media, owners, self.media)
        self.assertTrue(all(not owner['components'][0].get('terms_rule') for owner in owners.values()))

    def test_module_without_lgpl_alternative_stays_unresolved(self):
        self.document['packages'][0]['licenseConcluded'] = 'GPL-3.0-only OR LicenseRef-Missing'
        self.documents()
        owners = self.owners()
        qt = audit.qt_evidence(self.media, owners, self.media)
        providers = {'media': self.media}
        for name, document in {
                'app': {'crates': [], 'binary': {'rust_standard_library': {'archives': []}, 'direct_objects': []}},
                'runtime': {'components': []}, 'stage': {'packages': []}}.items():
            directory = self.media / name
            directory.mkdir()
            providers[name] = directory
            filename = 'ubuntu-sources.json' if name == 'stage' else 'manifest.json'
            (directory / filename).write_text(json.dumps(document))
        registry, _, _ = audit.load('components').registry(providers, owners, qt, {'components': []}, audit.stage.digest)
        self.assertTrue(registry)
        for owner in owners.values():
            self.assertIsNone(owner['components'][0]['selected_terms'])
            self.assertFalse(owner['components'][0]['terms_resolved'])

    def test_changed_vendor_backend_remains_rejected(self):
        self.backend.write_bytes(b'changed backend')
        with self.assertRaisesRegex(ValueError, 'Qt vendor SBOM checksum mismatch'):
            audit.qt_evidence(self.media, self.owners(), self.media)


class MediaProgramAttributionTests(unittest.TestCase):
    def setUp(self):
        temporary = tempfile.TemporaryDirectory()
        self.addCleanup(temporary.cleanup)
        self.media = Path(temporary.name)
        self.prefix = self.media / 'prefix'
        self.prefix.mkdir()
        self.file('bin/mpv', b'\x7fELF provider mpv program')
        self.file('lib/libmpv.so.2', b'checked provider shared library')
        for name in ('qtbase', 'qtdeclarative', 'qtsvg', 'qtshadertools'):
            self.file('sbom/' + name + '-6.11.2.spdx.json',
                      json.dumps({'name': name, 'packages': [], 'files': [], 'relationships': []}).encode())

    def file(self, relative, content):
        path = self.prefix / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(content)
        return path

    def test_seeded_provider_program_shares_checked_mpv_component(self):
        owners = {'usr/bin/mpv': {'owner': 'media', 'source': 'bin/mpv'},
                  'usr/lib/libmpv.so.2': {'owner': 'media', 'source': 'lib/libmpv.so.2'}}
        audit.qt_evidence(self.media, owners, self.media)
        for owner in owners.values():
            component = owner['components'][0]
            self.assertEqual(component['component_id'], 'mpv')
            self.assertEqual(component['license_expression'], 'GPL-2.0-or-later')

    def test_unrelated_or_inexact_provider_programs_remain_refused(self):
        for source in ('bin/ffmpeg', 'bin/ffprobe', 'bin/mpv-tool', 'mpv', 'usr/bin/mpv'):
            owners = {'usr/bin/mpv': {'owner': 'media', 'source': source}}
            with self.assertRaisesRegex(ValueError, 'media owner lacks component mapping'):
                audit.qt_evidence(self.media, owners, self.media)

    def test_required_executables_include_staged_provider_program(self):
        root = self.media / 'AppDir'
        (root / 'usr/bin').mkdir(parents=True)
        (root / 'AppRun').write_bytes(b'#!/bin/sh\n')
        (root / 'usr/bin/furami').write_bytes(b'\x7fELF application')
        for relative in ('AppRun', 'usr/bin/furami'):
            (root / relative).chmod(0o755)
        with self.assertRaisesRegex(ValueError, 'not executable by recipients: usr/bin/mpv'):
            audit.verify_executables(root, audit.REQUIRED_EXECUTABLES)
        program = root / 'usr/bin/mpv'
        program.write_bytes(b'\x7fELF provider mpv program')
        with self.assertRaisesRegex(ValueError, 'not executable by recipients: usr/bin/mpv'):
            audit.verify_executables(root, audit.REQUIRED_EXECUTABLES)
        program.chmod(0o755)
        audit.verify_executables(root, audit.REQUIRED_EXECUTABLES)


class MediaProgramClosureTests(unittest.TestCase):
    def setUp(self):
        temporary = tempfile.TemporaryDirectory()
        self.addCleanup(temporary.cleanup)
        self.root = Path(temporary.name) / 'payload'
        self.root.mkdir()

    def file(self, relative, data=b'ELF contents'):
        target = self.root / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
        return target

    def metadata(self, path, needed=(), runpath=None):
        return {'path': path, 'needed': list(needed), 'runpath': runpath, 'rpath': None,
                'class': 'ELF64', 'machine': 'Advanced Micro Devices X86-64'}

    def hashes(self, *targets):
        return {relative: hashlib.sha256((self.root / relative).read_bytes()).hexdigest()
                for relative in targets}

    def test_seeded_program_missing_unsearched_and_escaped_paths_are_reported(self):
        self.file('usr/bin/mpv')
        self.file('usr/private/libstaged.so.9')
        entries = [self.metadata('usr/bin/mpv', needed=['libabsent.so.9', 'libstaged.so.9'],
                                 runpath='$ORIGIN/../lib'),
                   self.metadata('usr/private/libstaged.so.9')]
        warnings = []
        dependencies = audit.inventory.resolve_dependency_closure(
            str(self.root), entries, self.hashes('usr/bin/mpv', 'usr/private/libstaged.so.9'),
            [], ['../outside', 'usr/missing-lib'], warnings)
        self.assertEqual({entry['resolution']['kind'] for entry in dependencies}, {'missing'})
        self.assertIn('missing dependency: libabsent.so.9 (required by usr/bin/mpv)', warnings)
        self.assertTrue(any('not in loader search paths' in warning for warning in warnings))
        self.assertTrue(any('escapes staged root' in warning for warning in warnings))
        self.assertTrue(any('library search path absent' in warning for warning in warnings))


if __name__ == '__main__':
    unittest.main()
